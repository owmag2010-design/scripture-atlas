// Merge content/discoveries/*.json into public/js/discoveries-data.js, checking every entry against the research rules.
// To add a discovery: add an object to a JSON file in content/discoveries/ (see README there), then run
//   node scripts/build-discoveries.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { BOOKS } from "../public/js/books.js";
import { validate } from "../public/js/discoveries.js";

const dir = new URL("../content/discoveries/", import.meta.url);
const files = readdirSync(dir).filter(f => f.endsWith(".json")).sort();
const all = files.flatMap(f => JSON.parse(readFileSync(new URL(f, dir), "utf8")).map(d => ({ ...d, _file: f })));
const bi = code => BOOKS.findIndex(b => b.osis === code);
const dataFile = n => new URL(`../public/data/hist/${n}.json`, import.meta.url);
const ctx = { bookIndex: bi };
if (existsSync(dataFile("people"))) ctx.people = new Set(JSON.parse(readFileSync(dataFile("people"))).map(p => p[0]));
if (existsSync(dataFile("places"))) ctx.places = new Set(JSON.parse(readFileSync(dataFile("places"))).map(p => p[0]));
const seen = new Set(); let bad = 0;
for (const d of all) {
  const errs = validate(d, ctx);
  if (seen.has(d.id)) errs.push("duplicate id");
  seen.add(d.id);
  if (errs.length) { bad++; console.error(`${d._file} ${d.id}: ${errs.join("; ")}`); }
}
if (bad) { console.error(`${bad} entr${bad === 1 ? "y has" : "ies have"} problems; nothing written.`); process.exit(1); }
const clean = all.map(({ _file, ...d }) => d);
writeFileSync(new URL("../public/js/discoveries-data.js", import.meta.url),
  `// Discovery entries, generated by scripts/build-discoveries.mjs from content/discoveries/*.json. Edit the JSON, not this file.\nexport const DISCOVERIES = ${JSON.stringify(clean, null, 1)};\n`);
console.log(`${clean.length} discoveries from ${files.length} files.`);
